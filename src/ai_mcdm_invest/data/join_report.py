"""Join report: whether the join kept the companies the study is about.

The report counts, per fiscal year, the companies and tail losers at each join
step, shows 20 random figure-match recoveries to check by eye, and is
rewritten on every build. The build stops when fiscal 2017 coverage falls
well short of the prototype's.
"""

import pandas as pd

from ai_mcdm_invest.data.panel import KEY_COLUMNS

# Fiscal 2017 is the year the prototype measured: 87.6% of companies and 90.6%
# of tail losers linked. The build stops when the join falls well below that.
COVERAGE_YEAR = 2017
MIN_COMPANY_COVERAGE = 0.85
MIN_TAIL_LOSER_COVERAGE = 0.88

# Recovered matches shown for checking by eye, drawn with a fixed seed so the
# report changes only when the join does.
SAMPLE_SIZE = 20
SAMPLE_SEED = 0

# Each step is a set of clean-panel rows. The first is everything; "linked by
# ticker" and "recovered by figures" split the linked rows, "unlinked" and
# "duplicates dropped" are the rows lost, and "joined panel" what is left.
STEPS = [
    "clean panel",
    "linked by ticker",
    "recovered by figures",
    "unlinked",
    "duplicates dropped",
    "joined panel",
]


def join_steps(clean: pd.DataFrame, links: pd.DataFrame, joined: pd.DataFrame) -> pd.DataFrame:
    """Companies and tail losers at each join step, per fiscal year.

    Indexed by `fiscal_year` and `step` (in `STEPS` order), with columns
    `companies` and `tail_losers`. A row is "linked by ticker" when today's
    ticker list gives the filer it is linked to, and "recovered by figures"
    when only its figures found that filer (renamed, delisted or reused tickers).
    """
    rows = clean[[*KEY_COLUMNS, "tail_loss"]].merge(
        links[[*KEY_COLUMNS, "cik", "ticker_cik", "link_method"]],
        on=KEY_COLUMNS,
        validate="one_to_one",
    )
    kept = joined[KEY_COLUMNS].assign(_kept=True)
    rows = rows.merge(kept, how="left", on=KEY_COLUMNS)
    rows["_kept"] = rows["_kept"].eq(True)

    linked = rows["link_method"] != "unlinked"
    recovered = recovered_by_figures(rows)
    in_step = {
        "clean panel": pd.Series(True, index=rows.index),
        "linked by ticker": linked & ~recovered,
        "recovered by figures": recovered,
        "unlinked": ~linked,
        "duplicates dropped": linked & ~rows["_kept"],
        "joined panel": rows["_kept"],
    }
    tables = []
    for step in STEPS:
        members = rows[in_step[step]]
        table = members.groupby("fiscal_year")["tail_loss"].agg(companies="size", tail_losers="sum")
        tables.append(table.assign(step=step))
    years = sorted(rows["fiscal_year"].unique())
    index = pd.MultiIndex.from_product([years, STEPS], names=["fiscal_year", "step"])
    steps = pd.concat(tables).set_index("step", append=True).reindex(index, fill_value=0)
    return steps.astype(int)


def recovered_by_figures(links: pd.DataFrame) -> pd.Series:
    """Rows linked by their figures to a filer today's ticker list does not give them."""
    return (links["link_method"] == "figure_match") & links["cik"].ne(links["ticker_cik"]).fillna(
        True
    )


def coverage(steps: pd.DataFrame) -> pd.Series:
    """Share of fiscal 2017's clean-panel companies and tail losers linked to a filer."""
    year = steps.loc[COVERAGE_YEAR]
    return (year.loc["clean panel"] - year.loc["unlinked"]) / year.loc["clean panel"]


class JoinCoverageTooLow(Exception):
    """The join links too few companies or tail losers to build the study on."""


def check_join_coverage(steps: pd.DataFrame) -> None:
    """Raise `JoinCoverageTooLow` if fiscal 2017's linked share is well below the prototype's.

    Coverage is the share of clean-panel rows linked to a filer. Rows dropped
    as duplicates do not count against it: their company is kept.
    """
    share = coverage(steps)
    shortfalls = [
        f"{share[column]:.1%} of {label} (minimum {minimum:.0%})"
        for column, label, minimum in [
            ("companies", "companies", MIN_COMPANY_COVERAGE),
            ("tail_losers", "tail losers", MIN_TAIL_LOSER_COVERAGE),
        ]
        if share[column] < minimum
    ]
    if shortfalls:
        raise JoinCoverageTooLow(
            f"fiscal {COVERAGE_YEAR} join links only {' and '.join(shortfalls)}; "
            "see the join report"
        )


def render_join_report(
    steps: pd.DataFrame, links: pd.DataFrame, sample_size: int = SAMPLE_SIZE
) -> str:
    """The join report as Markdown: step counts per year and a sample of recoveries."""
    share = coverage(steps)
    recovered = links[recovered_by_figures(links)].sort_values(KEY_COLUMNS)
    sample = recovered.sample(min(sample_size, len(recovered)), random_state=SAMPLE_SEED)
    lines = [
        "# Join report",
        "",
        "Regenerated by every build. Each clean-panel row is linked to an SEC filer by",
        "today's ticker list or recovered by its own figures; unlinked rows and",
        "duplicate rows of one filer (other share classes, preferred shares, notes)",
        "are lost before the joined panel.",
        "",
        f"Coverage check, fiscal {COVERAGE_YEAR}: {share['companies']:.1%} of companies and "
        f"{share['tail_losers']:.1%} of tail losers linked (the build stops below "
        f"{MIN_COMPANY_COVERAGE:.0%} and {MIN_TAIL_LOSER_COVERAGE:.0%}).",
        "",
        "## Companies",
        "",
        *_step_table(steps["companies"]),
        "",
        "## Tail losers",
        "",
        *_step_table(steps["tail_losers"]),
        "",
        "## Recovered matches",
        "",
        f"{len(sample)} of the {len(recovered)} rows recovered by figures, drawn at random "
        f"(seed {SAMPLE_SEED}). The ticker's CIK is what today's ticker list gives; empty "
        "when the ticker is no longer listed.",
        "",
        *_markdown_table(
            ["ticker", "fiscal year", "filer", "CIK", "ticker's CIK", "period end", "matched"],
            [
                [
                    row.ticker,
                    row.fiscal_year,
                    row.filer_name,
                    row.cik,
                    "" if pd.isna(row.ticker_cik) else row.ticker_cik,
                    row.period_end,
                    _matched_figures(row.matched_revenue, row.matched_net_income),
                ]
                for row in sample.sort_values(KEY_COLUMNS).itertuples()
            ],
        ),
    ]
    return "\n".join(lines) + "\n"


def _step_table(counts: pd.Series) -> list[str]:
    years = counts.index.get_level_values("fiscal_year").unique()
    return _markdown_table(
        ["fiscal year", *STEPS],
        [[year, *(counts[(year, step)] for step in STEPS)] for year in years],
    )


def _matched_figures(revenue: bool, net_income: bool) -> str:
    return " + ".join(
        ["total assets"] + ["revenue"] * bool(revenue) + ["net income"] * bool(net_income)
    )


def _markdown_table(header: list[str], rows: list[list]) -> list[str]:
    return [
        "| " + " | ".join(header) + " |",
        "|" + "---|" * len(header),
        *("| " + " | ".join(str(cell) for cell in row) + " |" for row in rows),
    ]
